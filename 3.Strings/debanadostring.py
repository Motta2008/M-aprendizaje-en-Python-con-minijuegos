cadena = "Este es un ejemplo de Substring (Debanado de cadenas)"

print(len(cadena))  # Longitud de la cadena

print(cadena[2])  # Caracter en la posición 2

print(cadena[5:15])  # Subcadena desde la posición 5 hasta la 15

print(cadena[ : 20])  # Subcadena desde el inicio hasta la posición 20

print(cadena[20 : ])  # Subcadena desde la posición 20 hasta el final

print(cadena[-1])  # Último carácter

print(cadena[-3])  # Tercer carácter desde el final