cadena = 'estoy utilizando los metodos de python'
cadena2 = 'ESTOY UTILIZANDO LOS METODOS DE PYTHON'


print(cadena2.lower())  # Convierte a minúsculas

print(cadena.upper())  # Convierte a mayúsculas

print(cadena.capitalize())  # Mayúscula en la primera letra

print(cadena.title())  # Mayúscula en la primera letra de cada palabra

print(cadena.swapcase())  # Intercambia mayúsculas y minúsculas